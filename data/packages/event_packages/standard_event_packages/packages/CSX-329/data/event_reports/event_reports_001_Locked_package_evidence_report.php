&nbsp;
<p>
CRW's most recent <a href="/satellite/bleachingoutlook_cfs/outlook_cfs.php">Four-Month Coral Bleaching Outlook</a> (Figure 4) 
projects heat stress will elevate to Alert Level 2 around Guam and the Federated States of Micronesia by the end of September and 
likely remain through November. The Hawaiian Islands are expected to be in a Bleaching Warning through most of October and November 2020, 
with the highest stress happening farther north of the islands around 30 &deg;N latitude.
</p>

