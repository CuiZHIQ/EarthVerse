<p>
<font size='-0.5'>
<b><i>Current conditions: </i></b></font>

<p>
NOAA Coral Reef Watch's (CRW) <a href="/index.php">near real-time satellite monitoring</a> shows the sea surface 
temperature (SST) as alternating between below- and above-average, but predominantly below-average, along the equator in the eastern and 
central equatorial Pacific; as being below-average in the southeast Pacific; and as being above-average throughout the remainder of the ocean 
basin (Figure 1). Anomalies remained between one and two degrees above normal for most of June, July and August 2020 around Hawaii, Fiji, American 
Samoa and Guam. The <a href="http://www.cpc.ncep.noaa.gov/products/analysis_monitoring/enso_advisory/ensodisc.html" target="_blank">El Ni&ntildeo Southern Oscillation (ENSO) 
Alert System</a> status (as of August 13, 2020) is: La Ni&ntildea Watch. La Ni&ntildea conditions are slightly favored over 
ENSO-neutral conditions for August-October 2020.
</p>

