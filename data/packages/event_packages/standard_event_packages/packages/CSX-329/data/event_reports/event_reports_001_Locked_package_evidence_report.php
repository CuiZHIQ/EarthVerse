<p>
Coral Bleaching HotSpots remained consistently low (&lt;1 &deg;C) throughout the Pacific these last few months. Only recently, in August, did 
they elevate above 1 &deg;C around Guam and the Commonwealth of the Northern Mariana Islands (CNMI) (Figure 2). Bleaching Alert Level 1 and 2 
conditions (conducive to significant bleaching, and severe bleaching and significant coral mortality, respectively) diminished around American Samoa 
in early June, and the majority of the Pacific remained under a Bleaching Watch in June and July (Figure 3). Guam and the CNMI have been under a 
Bleaching Warning since August. The highest alerts (Alert Level 2) have been concentrated around Taiwan and Japan in the northwest Pacific Ocean, 
as well as the South China Sea, with Taiwan reporting its most severe bleaching event on record.
</p>

